package com.terrainlab.item;

import com.terrainlab.TerrainLab;
import com.terrainlab.registry.ModDataComponents;
import com.terrainlab.registry.ModItems;
import net.minecraft.core.BlockPos;
import net.minecraft.core.component.DataComponents;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.saveddata.maps.MapId;
import net.minecraft.world.level.saveddata.maps.MapItemSavedData;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.server.ServerStoppedEvent;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.HashMap;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.ThreadFactory;

/**
 * Runs {@link AtlasMapGenerator} on a background thread, either for a fresh Atlas
 * in a player's inventory or ahead of time when a Cartographer reaches Master
 * (the result is queued and attached to the next fresh Atlas).
 * <p>
 * All queue state belongs to the running server and is cleared when it stops.
 */
@EventBusSubscriber(modid = TerrainLab.MODID)
public final class AtlasGenerationQueue {

    private AtlasGenerationQueue() {}

    private static final ExecutorService EXECUTOR =
            Executors.newSingleThreadExecutor(daemonThreadFactory());

    /** Maps pre-generated by Master Cartographers, already registered with the level. */
    private static final Deque<PreparedAtlas> PREPARED_ATLASES =
            new ArrayDeque<>();

    /** Origins currently being pre-generated; guards against duplicate jobs. */
    private static final Deque<PreparedOrigin> PREPARING =
            new ArrayDeque<>();

    /**
     * Number of running on-demand jobs per stack origin. A stack whose pending origin has no running
     * job lost its result (holder offline, stack moved, failure or server stop) and is queued again.
     */
    private static final Map<BlockPos, Integer> IN_FLIGHT =
            new HashMap<>();

    /** Incremented on server stop so completions started by an earlier server are dropped. */
    private static volatile int serverEpoch = 0;

    private static ThreadFactory daemonThreadFactory() {
        return runnable -> {
            Thread thread = new Thread(
                    runnable,
                    "TerrainLab-AtlasGeneration"
            );
            thread.setDaemon(true);
            return thread;
        };
    }

    /**
     * Attaches a pre-generated map to a fresh Atlas if one is available,
     * otherwise starts background generation from the player's position.
     */
    public static void ensureQueued(
            ServerLevel level,
            ServerPlayer player,
            ItemStack stack
    ) {
        if (!isUntouched(stack)) {
            return;
        }

        if (consumePreparedAtlas(level, player, stack)) {
            return;
        }

        BlockPos origin = player.blockPosition();

        stack.set(
                ModDataComponents.ATLAS_PENDING_ORIGIN.get(),
                origin
        );

        // TerrainLab.LOGGER.info(
                // "[Atlas] queued background generation for "
                        // + player.getScoreboardName()
                        // + " at origin=" + origin
        // );

        UUID playerId = player.getUUID();
        int epoch = serverEpoch;

        synchronized (IN_FLIGHT) {
            IN_FLIGHT.merge(origin, 1, Integer::sum);
        }

        CompletableFuture
                .supplyAsync(
                        () -> AtlasMapGenerator.generate(level, origin),
                        EXECUTOR
                )
                .whenComplete((data, throwable) ->
                        level.getServer().execute(() -> {
                            if (epoch != serverEpoch) {
                                return;
                            }

                            releaseInFlight(origin);

                            if (throwable != null) {
                                TerrainLab.LOGGER.error(
                                        "[Atlas] background generation failed for origin="
                                                + origin,
                                        throwable
                                );
                                return;
                            }

                            finish(
                                    level,
                                    playerId,
                                    origin,
                                    data
                            );
                        })
                );
    }

    /** Starts pre-generation centred on a Cartographer that reached Master (Overworld only). */
    public static void queuePreGeneratedAtlas(
            ServerLevel level,
            BlockPos origin
    ) {
        if (level.dimension() != Level.OVERWORLD) {
            return;
        }

        PreparedOrigin preparedOrigin =
                new PreparedOrigin(
                        level.dimension(),
                        origin
                );

        int epoch = serverEpoch;

        synchronized (PREPARING) {
            if (containsPrepared(preparedOrigin)
                    || PREPARING.contains(preparedOrigin)) {
                return;
            }

            PREPARING.addLast(preparedOrigin);
        }

        // TerrainLab.LOGGER.info(
                // "[Atlas] Master Cartographer triggered background generation"
                        // + " at origin=" + origin
        // );

        CompletableFuture
                .supplyAsync(
                        () -> AtlasMapGenerator.generate(level, origin),
                        EXECUTOR
                )
                .whenComplete((data, throwable) ->
                        level.getServer().execute(() -> {
                            if (epoch != serverEpoch) {
                                return;
                            }

                            synchronized (PREPARING) {
                                PREPARING.remove(preparedOrigin);
                            }

                            if (throwable != null) {
                                TerrainLab.LOGGER.error(
                                        "[Atlas] pre-generation failed for origin="
                                                + origin,
                                        throwable
                                );
                                return;
                            }

                            MapId mapId = level.getFreeMapId();
                            level.setMapData(mapId, data);

                            PreparedAtlas prepared =
                                    new PreparedAtlas(
                                            level.dimension(),
                                            origin,
                                            mapId
                                    );

                            synchronized (PREPARED_ATLASES) {
                                PREPARED_ATLASES.addLast(prepared);
                            }

                            // TerrainLab.LOGGER.info(
                                    // "[Atlas] pre-generation complete"
                                            // + " origin=" + origin
                                            // + " mapId=" + mapId
                            // );
                        })
                );
    }

    /**
     * True for a fresh Atlas with no map ID and no pending background job. Server-side only: a pending
     * marker whose job no longer runs is cleared first, so the stack is treated as fresh again.
     */
    public static boolean isUntouched(ItemStack stack) {
        if (!stack.is(ModItems.ATLAS.get())
                || stack.get(DataComponents.MAP_ID) != null) {
            return false;
        }

        clearOrphanedPending(stack);

        return stack.get(
                ModDataComponents.ATLAS_PENDING_ORIGIN.get()
        ) == null;
    }

    /**
     * True while on-demand generation for this stack is running. Server-side only: a pending marker
     * whose job no longer runs is cleared and reported as not pending.
     */
    public static boolean isPending(ItemStack stack) {
        if (stack.get(DataComponents.MAP_ID) != null) {
            return false;
        }

        clearOrphanedPending(stack);

        return stack.get(
                ModDataComponents.ATLAS_PENDING_ORIGIN.get()
        ) != null;
    }

    /** Clears all queue state when the server stops; prepared maps belong to that server's world. */
    @SubscribeEvent
    public static void onServerStopped(ServerStoppedEvent event) {
        serverEpoch++;

        synchronized (PREPARED_ATLASES) {
            PREPARED_ATLASES.clear();
        }

        synchronized (PREPARING) {
            PREPARING.clear();
        }

        synchronized (IN_FLIGHT) {
            IN_FLIGHT.clear();
        }
    }

    private static void clearOrphanedPending(ItemStack stack) {
        BlockPos origin = stack.get(
                ModDataComponents.ATLAS_PENDING_ORIGIN.get()
        );

        if (origin == null) {
            return;
        }

        boolean running;
        synchronized (IN_FLIGHT) {
            running = IN_FLIGHT.containsKey(origin);
        }

        if (!running) {
            stack.remove(
                    ModDataComponents.ATLAS_PENDING_ORIGIN.get()
            );
        }
    }

    private static void releaseInFlight(BlockPos origin) {
        synchronized (IN_FLIGHT) {
            IN_FLIGHT.computeIfPresent(
                    origin,
                    (key, count) -> count > 1 ? count - 1 : null
            );
        }
    }

    /** Attaches the oldest prepared map for this dimension to the stack, if any. */
    private static boolean consumePreparedAtlas(
            ServerLevel level,
            ServerPlayer player,
            ItemStack stack
    ) {
        PreparedAtlas prepared = null;

        synchronized (PREPARED_ATLASES) {
            for (PreparedAtlas candidate : PREPARED_ATLASES) {
                if (candidate.dimension().equals(level.dimension())) {
                    prepared = candidate;
                    break;
                }
            }

            if (prepared != null) {
                PREPARED_ATLASES.remove(prepared);
            }
        }

        if (prepared == null) {
            return false;
        }

        stack.set(
                DataComponents.MAP_ID,
                prepared.mapId()
        );

        // TerrainLab.LOGGER.info(
                // "[Atlas] attached pre-generated mapId="
                        // + prepared.mapId()
                        // + " to "
                        // + player.getScoreboardName()
                        // + " from origin="
                        // + prepared.origin()
        // );

        player.sendOverlayMessage(Component.literal(
                        "Your Atlas has finished mapping the region."
                ));

        return true;
    }

    /** Registers the generated map and stamps it onto the pending stack; runs on the server thread. */
    private static void finish(
            ServerLevel level,
            UUID playerId,
            BlockPos origin,
            MapItemSavedData data
    ) {
        ServerPlayer player =
                level.getServer()
                        .getPlayerList()
                        .getPlayer(playerId);

        if (player == null) {
            // TerrainLab.LOGGER.info(
                    // "[Atlas] generation finished for origin="
                            // + origin
                            // + " but player is offline - discarding"
            // );
            return;
        }

        ItemStack target =
                findPendingStack(
                        player,
                        origin
                );

        if (target == null) {
            // TerrainLab.LOGGER.info(
                    // "[Atlas] generation finished for origin="
                            // + origin
                            // + " but no matching pending stack found for "
                            // + player.getScoreboardName()
                            // + " - discarding"
            // );
            return;
        }

        MapId mapId = level.getFreeMapId();
        level.setMapData(mapId, data);

        target.set(
                DataComponents.MAP_ID,
                mapId
        );

        target.remove(
                ModDataComponents.ATLAS_PENDING_ORIGIN.get()
        );

        // TerrainLab.LOGGER.info(
                // "[Atlas] generation complete and stamped for "
                        // + player.getScoreboardName()
                        // + " origin=" + origin
                        // + " mapId=" + mapId
        // );

        player.sendOverlayMessage(Component.literal(
                        "Your Atlas has finished mapping the region."
                ));
    }

    private static ItemStack findPendingStack(
            ServerPlayer player,
            BlockPos origin
    ) {
        for (int slot = 0;
             slot < player.getInventory().getContainerSize();
             slot++) {

            ItemStack stack =
                    player.getInventory().getItem(slot);

            if (matchesPending(stack, origin)) {
                return stack;
            }
        }

        return null;
    }

    private static boolean matchesPending(
            ItemStack stack,
            BlockPos origin
    ) {
        if (!stack.is(ModItems.ATLAS.get())) {
            return false;
        }

        if (stack.get(DataComponents.MAP_ID) != null) {
            return false;
        }

        return origin.equals(
                stack.get(
                        ModDataComponents.ATLAS_PENDING_ORIGIN.get()
                )
        );
    }

    private static boolean containsPrepared(
            PreparedOrigin origin
    ) {
        synchronized (PREPARED_ATLASES) {
            for (PreparedAtlas prepared : PREPARED_ATLASES) {
                if (prepared.dimension().equals(origin.dimension())
                        && prepared.origin().equals(origin.origin())) {
                    return true;
                }
            }
        }

        return false;
    }

    private record PreparedAtlas(
            ResourceKey<Level> dimension,
            BlockPos origin,
            MapId mapId
    ) {}

    private record PreparedOrigin(
            ResourceKey<Level> dimension,
            BlockPos origin
    ) {}
}
